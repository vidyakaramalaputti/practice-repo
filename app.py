# For Loop: Iterates over a specific sequence (prints 1 to 5)
print("Counting from 1 to 5:")
for i in range(1, 6):
    print(i)

# While Loop: Keeps running as long as a condition remains True
countdown = 3
print("Starting countdown...")
while countdown > 0:
    print(countdown)
    countdown -= 1  # Subtract 1 from countdown
print("Blast off!")

